package com.pfmanager.contribution.dto;

import com.pfmanager.contribution.enums.EntryType;
import io.swagger.v3.oas.annotations.media.Schema;
import lombok.Builder;

import java.math.BigDecimal;
import java.time.Instant;
import java.time.LocalDate;
import java.util.UUID;

/**
 * Response body representing a single contribution ledger entry.
 * Returned by POST /api/v1/contributions (201) and GET /api/v1/contributions/{transactionId} (200).
 */
@Builder
@Schema(description = "A single contribution ledger entry")
public record ContributionResponse(

        @Schema(description = "Unique transaction ID generated by the service")
        UUID transactionId,

        @Schema(description = "Participant identifier", example = "PF-10001")
        String participantId,

        @Schema(description = "CONTRIBUTION or REVERSAL")
        EntryType entryType,

        @Schema(description = "Positive decimal amount", example = "2500.00")
        BigDecimal amount,

        @Schema(description = "ISO 4217 currency code", example = "INR")
        String currency,

        @Schema(description = "Business effective date", example = "2026-10-29")
        LocalDate effectiveDate,

        @Schema(description = "UTC timestamp when the entry was recorded")
        Instant recordedAt,

        @Schema(description = "Optional external/business reference", example = "PAYROLL-OCT-2026-10001")
        String reference,

        @Schema(description = "Optional short description")
        String note,

        @Schema(description = "For REVERSAL entries: the original transaction ID that was reversed")
        UUID reversesTransactionId,

        @Schema(description = "Optional caller or system identity")
        String createdBy
) {}
