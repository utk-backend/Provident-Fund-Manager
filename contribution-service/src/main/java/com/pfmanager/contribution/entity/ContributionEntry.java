package com.pfmanager.contribution.entity;

import com.pfmanager.contribution.enums.EntryType;
import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;

import java.math.BigDecimal;
import java.time.Instant;
import java.time.LocalDate;
import java.util.UUID;

/**
 * Immutable ledger entry representing a single contribution or reversal.
 * <p>
 * Entries are append-only. Corrections create new rows rather than modifying
 * or deleting existing ones. No update or delete operations are exposed via
 * normal API flows.
 */
@Entity
@Table(name = "contribution_entries")
@Getter
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class ContributionEntry {

    /**
     * Unique identifier for this ledger entry.
     * Generated by the service; immutable once set.
     */
    @Id
    @Column(name = "transaction_id", nullable = false)
    private UUID transactionId;

    /**
     * Reference to the participant who owns this ledger entry.
     * Enforced via FK constraint to the participants table.
     */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "participant_id", nullable = false)
    private Participant participant;

    /**
     * Whether this entry is a CONTRIBUTION (increases balance)
     * or a REVERSAL (decreases balance).
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "entry_type", nullable = false, length = 20)
    private EntryType entryType;

    /**
     * Positive decimal magnitude of the entry.
     * Uses DECIMAL(19,2) — never float or double.
     * The entry type determines its effect on the balance.
     */
    @Column(name = "amount", nullable = false, precision = 19, scale = 2)
    private BigDecimal amount;

    /**
     * ISO 4217 currency code. INR only in Phase 1.
     */
    @Column(name = "currency", nullable = false, length = 3)
    private String currency;

    /**
     * Business-supplied effective date of the contribution.
     * Cannot be in the future under the default Phase 1 policy.
     */
    @Column(name = "effective_date", nullable = false)
    private LocalDate effectiveDate;

    /**
     * UTC timestamp generated by the service when the entry was recorded.
     */
    @Column(name = "recorded_at", nullable = false)
    private Instant recordedAt;

    /**
     * Optional external/business reference (e.g., "PAYROLL-OCT-2026-10001").
     * Unique per participant when provided.
     */
    @Column(name = "reference", length = 100)
    private String reference;

    /** Optional short human-readable description of the entry. */
    @Column(name = "note", length = 500)
    private String note;

    /**
     * For REVERSAL entries: the transaction ID of the original contribution
     * being reversed. Null for CONTRIBUTION entries.
     */
    @Column(name = "reverses_transaction_id")
    private UUID reversesTransactionId;

    /**
     * Optional identifier of the caller or system that created this entry.
     */
    @Column(name = "created_by")
    private String createdBy;
}
