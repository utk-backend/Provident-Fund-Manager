package com.pfmanager.contribution.entity;

import com.pfmanager.contribution.enums.ParticipantStatus;
import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;

import java.time.Instant;

/**
 * Represents a Provident Fund participant.
 * <p>
 * This is a lean entity intended to support FK constraints and existence/status
 * checks for the Contribution Service. Full participant management is out of scope
 * for this iteration and will be handled by a dedicated service in the future.
 */
@Entity
@Table(name = "participants")
@Getter
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class Participant {

    /**
     * Stable business identifier for the participant (e.g., "PF-10001").
     * Assigned externally; not generated by this service.
     */
    @Id
    @Column(name = "participant_id", nullable = false, length = 50)
    private String participantId;

    /** Full name of the participant. */
    @Column(name = "name", nullable = false)
    private String name;

    /** Lifecycle status — contributions are only accepted for ACTIVE participants. */
    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false, length = 20)
    private ParticipantStatus status;

    /** UTC timestamp when this participant record was created. */
    @Column(name = "created_at", nullable = false)
    private Instant createdAt;
}
